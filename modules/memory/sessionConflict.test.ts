import test from 'ava';
import { readFileSync } from 'node:fs';
import { mergeSessionConflict, readConflictAwareSession, rawSessionBlocks } from './sessionConflict.js';
import { parseActiveSession, formatSessionEvent, maxSeq } from './activeSessionFormat.js';
import { sessionMessageId } from './sessionMessageIdentity.js';

const fixture = (name: string) => readFileSync(new URL(`./fixtures/session-conflict/${name}.md`, import.meta.url), 'utf8');
const conflict = fixture('sesja_konflikt_markery');
const conversation = [
    ['user', 'B0: poczatek wspolnej sesji, odpowiedz slowem baza'],
    ['assistant', 'baza'],
    ['user', 'A1: wiadomosc z telefonu, odpowiedz slowem telefon'],
    ['assistant', 'telefon'],
    ['user', 'B1: wiadomosc z laptopa, odpowiedz slowem laptop'],
    ['assistant', 'laptop'],
];
const header = '---\nagent: Jaskier\ntype: active_session\n---\n\n';
const a = '## 2026-11-14T10:00:00.000Z — user message\n\n**content:**\n\nA\n\n**seq:**\n\n1\n\n';
const b = '## 2026-11-14T10:00:01.000Z — agent message\n\n**content:**\n\nB\n\n**seq:**\n\n1\n\n';
const wrap = (ours: string, theirs: string) => `<<<<<<< HEAD\n${ours}=======\n${theirs}>>>>>>> remote\n`;

for (const crlf of [false, true]) for (const diff3 of [false, true]) test(`D7 real libgit2 conflict, raw union, CRLF=${crlf}, diff3=${diff3}`, t => {
    let input = conflict;
    if (diff3) input = input.replace(/^=======$/gm, '||||||| base\nignored base\n=======');
    if (crlf) input = input.replace(/\n/g, '\r\n');
    const result = mergeSessionConflict(input);
    t.is(result.kind, 'merged');
    if (result.kind !== 'merged') return;
    const parsed = parseActiveSession(result.text);
    t.deepEqual(parsed.messages.filter(m => m.role !== 'tool' && m.content).map(m => [m.role, m.content]), conversation);
    t.deepEqual(parsed.messages.map(m => [m.role, m.seq]), [
        ['user', 1], ['tool', 2], ['assistant', 3], ['tool', 4], ['assistant', 5],
        ['user', 6], ['assistant', 7], ['user', 6], ['assistant', 7],
    ]);
    t.is(parsed.messages[2].toolCalls?.[0].function.name, 'kom_list');
    t.is(parsed.metadata.epoch, '24c013732c84ddf9eade43ab0b43445e');
    // Independent slicing of source fixtures; expected raw blocks are never generated by the merger.
    const originals = ['sesja_strona_A', 'sesja_strona_B'].flatMap(name => {
        const source = crlf ? fixture(name).replace(/\n/g, '\r\n') : fixture(name);
        return source.split(/(?=^## )/m).slice(1);
    });
    const expected = [...new Set(originals)];
    t.deepEqual(rawSessionBlocks(result.text).blocks, expected);
    t.is(/^(?:<<<<<<<|=======|>>>>>>>)/m.test(result.text), false);
    t.is(maxSeq(result.text), 7);
    t.deepEqual(mergeSessionConflict(result.text), { kind: 'not-applicable' });
});

test('D7 derived metadata takes ours; ownership and unknown header changes are refused', t => {
    const input = header.replace('type: active_session\n', wrap('type: active_session\nupdated: today\nmessageCount: 2\n', 'type: active_session\nupdated: yesterday\nmessageCount: 3\n')) + wrap(a, b);
    t.deepEqual(mergeSessionConflict(input), { kind: 'merged', text: header.replace('type: active_session\n', 'type: active_session\nupdated: today\nmessageCount: 2\n') + a + b });
    for (const key of ['device', 'epoch', 'created', 'agent', 'type', 'taken_over', 'unknown']) {
        t.deepEqual(mergeSessionConflict(header.replace('type: active_session\n', wrap(`${key}: A\n`, `${key}: B\n`)) + a), { kind: 'unresolved' }, key);
    }
});

test('D7 healthy user example remains literal, including YAML-looking text in content', t => {
    const example = 'Przykład:\n```diff\n<<<<<<< HEAD\nupdated: A\n=======\nupdated: B\n>>>>>>> other\n```';
    const input = header + formatSessionEvent('user_message', { content: example, seq: 1 }, '2026-11-14T10:00:00.000Z');
    t.deepEqual(mergeSessionConflict(input), { kind: 'not-applicable' });
    t.deepEqual(readConflictAwareSession(input).messages, [{ role: 'user', content: example, seq: 1 }]);
    t.deepEqual(readConflictAwareSession(input), parseActiveSession(input));
});

test('D7c stable ties remain ordered; unnumbered divergent blocks refuse', t => {
    const tied = b.replace('10:00:01', '10:00:00');
    const unknown = '## unknown event\nopaque\n\n';
    t.deepEqual(mergeSessionConflict(header + wrap(a, tied)), { kind: 'merged', text: header + a + tied });
    t.deepEqual(mergeSessionConflict(header + wrap(a + unknown, tied)), { kind: 'unresolved' });
    t.deepEqual(mergeSessionConflict(header + wrap(b, a + unknown)), { kind: 'unresolved' });
});

test('D7 three sides: sequential resolved merge works; nested and incomplete conflicts refuse', t => {
    const first = mergeSessionConflict(header + wrap(a, b));
    t.deepEqual(first, { kind: 'merged', text: header + a + b });
    const c = b.replaceAll('B', 'C').replace('10:00:01', '10:00:02');
    t.deepEqual(mergeSessionConflict(header + wrap(a + b, a + c)), { kind: 'unresolved' });
    const b2 = b.replace('\n1\n', '\n2\n'), c2 = c.replace('\n1\n', '\n2\n');
    t.deepEqual(mergeSessionConflict(header + wrap(a + b2, a + c2)), { kind: 'merged', text: header + a + b2 + c2 });
    t.deepEqual(mergeSessionConflict(header + wrap(wrap(a, b), c)), { kind: 'unresolved' });
    t.deepEqual(mergeSessionConflict(header + '<<<<<<< HEAD\n' + a + '=======\n' + b), { kind: 'unresolved' });
});

test('D7 already-amplified 313df88 fixture can be read without further amplification', t => {
    const result = mergeSessionConflict(fixture('sesja_konflikt_po_kolejnej_turze_313df88'));
    t.is(result.kind, 'merged');
    if (result.kind !== 'merged') return;
    t.deepEqual(parseActiveSession(result.text).messages.filter(m => m.role !== 'tool' && m.content).map(m => [m.role, m.content]), [
        ...conversation, ['user', 'C1: po scaleniu, odpowiedz slowem dalej'], ['assistant', 'dalej'],
    ]);
    t.is(/^(?:<<<<<<<|=======|>>>>>>>)/m.test(result.text), false);
});

test('D7 seq duplicates do not identify messages; explicit deletion works, ambiguous legacy/ranges refuse', t => {
    const x = a.replace('**content:**', '**message_id:**\n\nx\n\n**content:**');
    const y = b.replace('**content:**', '**message_id:**\n\ny\n\n**content:**');
    const remove = (ids: string[], ranges: unknown[] = []) => formatSessionEvent('messages_removed', { removed_messages: ids, removed_ranges: ranges, seq: 2 }, '2026-11-14T10:00:03.000Z');
    const merged = mergeSessionConflict(header + wrap(x + remove(['x']), y));
    t.is(merged.kind, 'merged');
    if (merged.kind !== 'merged') return;
    t.deepEqual(parseActiveSession(merged.text).messages.map(m => [sessionMessageId(m), m.content, m.seq]), [['y', 'B', 1]]);
    t.deepEqual(mergeSessionConflict(header + wrap(a + remove(['legacy:1']), b)), { kind: 'unresolved' });
    t.deepEqual(mergeSessionConflict(header + wrap(x + remove(['x'], [{ from: 'x', to: 'y' }]), y)), { kind: 'unresolved' });
    const legacy = readConflictAwareSession(header + wrap(a, b));
    t.deepEqual(legacy.messages.map(m => [sessionMessageId(m), m.content, m.seq]), [['legacy:1', 'A', 1], ['legacy:2', 'B', 1]]);
});

test('D7 event epoch must agree on both sides and after ordering', t => {
    const epoch = (id: string) => formatSessionEvent('session_epoch', { epoch: id.repeat(32), seq: 2 }, '2026-11-14T10:00:03.000Z');
    t.deepEqual(mergeSessionConflict(header + wrap(a + epoch('a'), b + epoch('b'))), { kind: 'unresolved' });
    const merged = mergeSessionConflict(header + wrap(a + epoch('a'), b + epoch('a')));
    t.is(merged.kind, 'merged');
    if (merged.kind !== 'merged') return;
    t.deepEqual(parseActiveSession(merged.text).messages.map(m => [sessionMessageId(m), m.content]), [['legacy:1', 'A'], ['legacy:2', 'B']]);
    t.is(parseActiveSession(merged.text).metadata.epoch, 'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa');
});

test('D7c repeated seq refuses; identical unnumbered prefix repetitions survive', t => {
    t.deepEqual(mergeSessionConflict(header + wrap(a + a, a + b)), { kind: 'unresolved' });
    t.deepEqual(mergeSessionConflict(header + wrap(a, a + a + b)), { kind: 'unresolved' });
    const prefix = '## User\n\nCommon\n\n'.repeat(2);
    t.deepEqual(mergeSessionConflict(header + prefix + wrap(a, b)), { kind: 'merged', text: header + prefix + a + b });
});

test('D7 whole-file conflict recognizes frontmatter even before any first event', t => {
    t.deepEqual(mergeSessionConflict(wrap(header + 'unused\n', header.replace('agent: Jaskier', 'agent: Mira') + 'unused\n')), { kind: 'unresolved' });
    const ours = header.replace('type: active_session', 'updated: old\ntype: active_session');
    const theirs = header.replace('type: active_session', 'updated: new\ntype: active_session');
    t.deepEqual(mergeSessionConflict(wrap(ours, theirs)), { kind: 'merged', text: ours });
});
